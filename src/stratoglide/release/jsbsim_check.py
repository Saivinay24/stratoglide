def jsb_release(p, z0, pitch_deg, v_up, dt=0.01, t_end=120.0):
    import jsbsim
    root = write_aircraft(p)
    f = jsbsim.FGFDMExec(str(root), None)
    f.set_debug_level(0)
    f.load_model("stratoglide")
    f.set_dt(dt)
    f["ic/h-sl-ft"] = z0 / FT
    f["ic/theta-deg"] = pitch_deg
    f["ic/phi-deg"] = 0.0
    f["ic/psi-true-deg"] = 0.0
    f["ic/vn-fps"], f["ic/ve-fps"], f["ic/vd-fps"] = 0.0, 0.0, -v_up / FT
    f["ic/p-rad_sec"] = f["ic/q-rad_sec"] = f["ic/r-rad_sec"] = 0.0
    f.run_ic()
    ap = autopilot.PullOut(p, 1, "autopilot")
    rec = autopilot.Recovery(p, 1)
    nz_max, z_hist = -np.inf, []
    t = 0.0
    while t < t_end:
        z = f["position/h-sl-ft"] * FT
        V = f["velocities/vt-fps"] * FT
        rho = f["atmosphere/rho-slugs_ft3"] * SLUG3
        eas = V * np.sqrt(rho / 1.225)
        gamma = f["flight-path/gamma-rad"]
        w = np.array([[f["velocities/p-rad_sec"], f["velocities/q-rad_sec"], f["velocities/r-rad_sec"]]])
        alpha = f["aero/alpha-rad"]
        de, da, dr = ap.step(t, np.array([eas]), np.array([gamma]), w, np.array([f["attitude/phi-rad"]]), np.array([alpha]), np.array([V]), np.array([f["attitude/theta-rad"]]))
        f["sg/de-deg"], f["sg/da-deg"], f["sg/dr-deg"] = float(de[0]), float(da[0]), float(dr[0])
        rec.update(t, dt, np.array([gamma]), w, np.array([alpha]), np.array([z]))
        f.run()
        t += dt
        nz = -f["forces/fbz-aero-lbs"] * LB2N / (p["mass"] * 9.80665)
        nz_max = max(nz_max, nz)
    return {"recovered": bool(rec.recovered[0]), "alt_lost_m": float(z0 - rec.z_rec[0]), "t_rec_s": float(rec.t_rec[0]),
            "nz_max": float(nz_max)}


def own_release(p, z0, pitch_deg, v_up):
    X0 = np.zeros((1, 13))
    X0[:, 2] = -z0
    X0[:, 6:10] = sd.euler2q(np.zeros(1), np.array([pitch_deg * D2R]), np.zeros(1))
    R = sd.q2R(X0[:, 6:10])
    X0[:, 3:6] = np.einsum("nji,nj->ni", R, np.array([[0, 0, -v_up]]))
    r = sd.run(p, X0, sd.Wind([0, 40000], [0, 0], np.zeros(1)), mode="autopilot")
    return {"recovered": bool(r["recovered"][0]), "alt_lost_m": float(z0 - r["z_rec"][0]), "t_rec_s": float(r["t_rec"][0]),
            "nz_max": float(r["stats"]["nz"][0])}


def atmos_check(z=25000.0):
    import jsbsim
    root = write_aircraft(aero_tables.nominal())
    f = jsbsim.FGFDMExec(str(root), None)
    f.set_debug_level(0)
    f.load_model("stratoglide")
    f["ic/h-sl-ft"] = z / FT
    f["ic/vt-fps"] = 100.0
    f.run_ic()
    rho_j = f["atmosphere/rho-slugs_ft3"] * SLUG3
    T_j = f["atmosphere/T-R"] * 5 / 9
    a = isa(z)
    return {"z_m": z, "rho_jsbsim": rho_j, "rho_own": float(a["rho"]), "T_jsbsim": T_j, "T_own": float(a["T"]),
            "rho_rel": abs(rho_j / float(a["rho"]) - 1), "T_rel": abs(T_j / float(a["T"]) - 1)}


def main():
    m = load_cfg("mission")["release"]
    p = aero_tables.nominal()
    atm = atmos_check(m["alt_m"])
    pitch, v_up = m["pitch_deg"]["nominal"], float(np.mean(m["v_up_mps"]))
    j = jsb_release(p, m["alt_m"], pitch, v_up)
    o = own_release(p, m["alt_m"], pitch, v_up)
    out = {"atmosphere": atm, "nominal": {"pitch_deg": pitch, "v_up_mps": v_up, "jsbsim": j, "own": o,
           "alt_lost_rel": abs(j["alt_lost_m"] / o["alt_lost_m"] - 1), "peak_n_rel": abs(j["nz_max"] / o["nz_max"] - 1)}}
    write_json(phase_dir("p5") / "jsbsim_check.json", out)
    n = Numbers("p5", "src/stratoglide/release/jsbsim_check.py")
    n.add("jsbsim_rho_rel_25km", atm["rho_rel"])
    n.add("jsb_vs_own_alt_lost_rel", out["nominal"]["alt_lost_rel"])
    n.add("jsb_vs_own_peak_n_rel", out["nominal"]["peak_n_rel"])
    n.add("nominal_alt_lost_own_m", o["alt_lost_m"], "m"); n.add("nominal_alt_lost_jsb_m", j["alt_lost_m"], "m")
    n.add("nominal_nz_own", o["nz_max"], "g"); n.add("nominal_nz_jsb", j["nz_max"], "g")
    n.save()
    print(out)


if __name__ == "__main__":
    main()
